export function chooseLocale(language: Locale): void {
  locale.set(language);
  if (typeof document !== 'undefined') document.documentElement.lang = language;
  try { if (typeof localStorage !== 'undefined') localStorage.setItem(LANGUAGE_STORAGE_KEY, language); } catch { /* private mode */ }
}
export function restoreLocale(): void {
  let saved: Locale | null = null;
  try { if (typeof localStorage !== 'undefined') saved = parseLocale(localStorage.getItem(LANGUAGE_STORAGE_KEY)); } catch { /* private mode */ }
  chooseLocale(saved ?? 'en');
}
